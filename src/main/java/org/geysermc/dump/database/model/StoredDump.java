package org.geysermc.dump.database.model;

import org.geysermc.dump.checks.AbstractCheck;
import org.springframework.data.annotation.Id;
import org.springframework.data.relational.core.mapping.Table;
import tools.jackson.core.JacksonException;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.time.Instant;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.ServiceLoader;
import java.util.regex.Pattern;

@Table("dumps")
public record StoredDump(
    @Id String id,
    List<String> problems,
    String raw,
    Instant createdAt,
    boolean legacy
) {
    private static final List<AbstractCheck> CHECKS;

    private static final Pattern KEY_FORMAT = Pattern.compile("[a-f0-9]{32}");

    static {
        CHECKS = ServiceLoader.load(AbstractCheck.class).stream()
            .map(ServiceLoader.Provider::get)
            .toList();
    }

    /**
     * Check if a key from a dump url was generated by GeyserDump-js
     *
     * @param key the key from the url
     * @return true if the key is in the legacy format
     */
    public static boolean isLegacyKey(String key) {
        return !KEY_FORMAT.matcher(key).matches();
    }

    /**
     * Get the id a legacy dump is stored under, matching the file names used by the GeyserDump-js file store
     *
     * @param key the key from the url
     * @return the md5 hash of the key
     */
    public static String legacyId(String key) {
        try {
            byte[] hash = MessageDigest.getInstance("MD5").digest(key.getBytes(StandardCharsets.UTF_8));
            return HexFormat.of().formatHex(hash);
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    /**
     * Create a legacy dump from the GeyserDump-js file store
     *
     * @param id the md5 hash of the original key
     * @param raw the stored file contents
     * @param createdAt when the file was last modified
     * @throws JacksonException if the contents are not valid JSON
     * @return the legacy dump
     */
    public static StoredDump legacy(String id, String raw, Instant createdAt) throws JacksonException {
        JsonNode dump = JsonMapper.shared().readTree(raw);
        if (dump.isMissingNode()) {
            throw new IllegalArgumentException("Empty dump");
        }

        // GeyserDump-js accepted any JSON, so not every legacy dump can be checked
        List<String> problems;
        try {
            problems = checkIssues(dump);
        } catch (JacksonException ignored) {
            problems = List.of();
        }

        return new StoredDump(id, problems, raw, createdAt, true);
    }

    public static StoredDump from(String dumpData) {
        JsonNode dump;
        try {
            // Get json data from dump
            dump = JsonMapper.shared().readTree(dumpData);
            if (!dump.isObject()) {
                throw new IllegalArgumentException("Invalid dump");
            }

            // Check the dump isn't empty or an error message
            if (dump.isEmpty() || (dump.size() == 1 && dump.has("message"))) {
                throw new IllegalArgumentException("Empty dump");
            }

            dump.required("bootstrapInfo");
        } catch (JacksonException ignored) {
            throw new IllegalArgumentException("Invalid dump");
        }

        return new StoredDump(null, checkIssues(dump), dump.toString(), Instant.now(), false);
    }

    private static List<String> checkIssues(JsonNode dump) throws JacksonException {
        JsonNode platformNode = dump.required("bootstrapInfo").required("platform");
        String platform = "";
        if (platformNode.isString()) {
            platform = platformNode.stringValue();
        } else {
            platform = platformNode.required("platformName").stringValue().toUpperCase();
        }
        List<String> problems = new ArrayList<>();

        // Check plugins and stuff for potential issues
        for (AbstractCheck issueCheck : CHECKS) {
            if (issueCheck.compatiblePlatform(platform)) {
                try {
                    problems.addAll(issueCheck.checkIssues(dump));
                } catch (JacksonException ignored) {
                }
            }
        }

        return problems;
    }
}
